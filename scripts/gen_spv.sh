#!/bin/sh
# Compile shaders/*.comp to SPIR-V and embed them in src/eif_vk_shaders.h (committed, so normal builds
# need no shader compiler). Usage: scripts/gen_spv.sh [glslangValidator]
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
GLSLANG=${1:-${GLSLANG:-glslangValidator}}
command -v "$GLSLANG" >/dev/null 2>&1 || { echo "glslangValidator not found (pass its path as \$1)" >&2; exit 1; }
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
OUT="$ROOT/src/eif_vk_shaders.h"

# name  source  extra defines
VARIANTS="
gemm_f32      gemm.comp
gemm_q8       gemm.comp -DB_INT8
gemm_kn       gemm.comp -DB_KN
gemm_f32_big  gemm_vec.comp
gemm_q8_big   gemm_vec.comp -DB_INT8
layernorm     layernorm.comp
softmax       softmax.comp
bcast         bcast.comp
merge         merge.comp
attention     attention.comp
"

{
    echo "/* Generated by scripts/gen_spv.sh from the shaders/ directory - do not edit. */"
    echo "#ifndef EIF_VK_SHADERS_H"
    echo "#define EIF_VK_SHADERS_H"
    echo "#include <stdint.h>"
    echo "#include <stddef.h>"
} > "$TMP/hdr"

echo "$VARIANTS" | while read -r name src defs; do
    [ -n "$name" ] || continue
    # shellcheck disable=SC2086
    "$GLSLANG" -V --target-env vulkan1.0 $defs -o "$TMP/$name.spv" "$ROOT/shaders/$src" >"$TMP/log" || { cat "$TMP/log" >&2; exit 1; }
    python3 - "$TMP/$name.spv" "$name" >> "$TMP/hdr" <<'PY'
import struct, sys
data = open(sys.argv[1], 'rb').read()
words = struct.unpack('<%dI' % (len(data) // 4), data)
name = sys.argv[2]
print('\nstatic const uint32_t eif_spv_%s[%d] = {' % (name, len(words)))
for i in range(0, len(words), 8):
    print('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
print('};')
PY
done
echo "" >> "$TMP/hdr"
echo "#endif /* EIF_VK_SHADERS_H */" >> "$TMP/hdr"
mv "$TMP/hdr" "$OUT"
echo "wrote $OUT"
